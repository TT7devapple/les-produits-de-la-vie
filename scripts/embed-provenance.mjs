// Inscrit l'origine de chaque image livrée dans le fichier lui-même
// (règle de provenance Impeccable). Relancer après tout ajout ou remplacement d'image :
//   node scripts/embed-provenance.mjs
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const launcher = path.join(os.homedir(), ".claude/skills/impeccable/scripts", process.platform === "win32" ? "impeccable.cmd" : "impeccable");
// Le texte passe par un fichier : aucun souci d'échappement des espaces ou guillemets.
const tmp = path.join(os.tmpdir(), "lpdlv-provenance.txt");
const embed = (file, text) => {
  fs.writeFileSync(tmp, text, "utf8");
  execFileSync(launcher, ["embed-prompt", file, "--prompt-file", tmp], { stdio: "inherit", shell: process.platform === "win32" });
};

// Photos temporaires : origine lue dans CREDITS.md
const credits = fs.readFileSync("src/assets/images/CREDITS.md", "utf8");
for (const line of credits.split(/\r?\n/)) {
  const m = line.match(/^\| ([\w-]+\.jpg) \| (.*?) \| (.*?) \| \[(\w+)\]\((.*?)\) \| (\w+) \|$/);
  if (!m) continue;
  const [, file, title, creator, source, url, license] = m;
  const target = path.join("src/assets/images", file);
  if (!fs.existsSync(target)) continue;
  embed(target, `Sourced stock photo (temporary placeholder, to replace with real shop photos). Origin: "${title}" by ${creator}, ${source} (${url}), license ${license}, found via Openverse. Resized to max 2000px with sharp; some crops documented in CREDITS.md.`);
}

// Photos fournies par le client (vraies photos de la marque)
for (const file of ["jus-carotte-betterave-marque.jpg", "mandeletti-camelia.jpg", "comptoir-stand.jpg", "pesto-tartine.jpg"]) {
  embed(path.join("src/assets/images", file), "Client-supplied brand photo (Les Produits de la Vie), provided by the site owner in Sept. 2026. Converted from PNG to JPEG with sharp; mandeletti-camelia.jpg trimmed of a grey border (left 26px, top 14px).");
}

embed("public/textures/kraft.png", "Procedural texture generated by scripts/generate-textures.mjs (kraft paper fibres and specks, seeded PRNG, 256px seamless tile). No external source.");
embed("public/textures/ink.png", "Procedural mask generated by scripts/generate-textures.mjs (worn rubber-stamp ink holes, seeded PRNG, 192px tile). No external source.");
embed("src/app/apple-icon.png", "Rasterized with sharp from the authored SVG src/app/icon.svg (LP monogram, kraft ground, bordeaux ink square frame). No external source.");
embed("src/app/opengraph-image.jpg", "Screenshot of the site's own home first viewport at 1200x630 (Edge headless, reduced motion), with live daily values on the scale label replaced by timeless hours. Contains the temporary kraft texture only; no external imagery.");
